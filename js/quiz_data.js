// 에스라 성경 골든벨 / 모의고사용 랜덤 N문제 추출 함수
// 전체 성경 풀에서 무작위 추출 + 각 문제 보기 순서 무작위 셔플
// ============================================================================
function getRandomBibleQuizzes(count = 10) {
  const allQuizzes = [];

  // 전체 DB 수집
  Object.keys(BIBLE_QUIZ_DATABASE).forEach(bookName => {
    BIBLE_QUIZ_DATABASE[bookName].forEach(q => {
      allQuizzes.push({ ...q, bookName: bookName });
    });
  });

  // Fisher-Yates 셔플
  const shuffled = shuffleArray(allQuizzes);
  const selected = shuffled.slice(0, Math.min(count, shuffled.length));

  // 각 문제의 보기 순서도 셔플하여 반환
  return selected.map(q => randomizeQuizQuestion(q));
}

