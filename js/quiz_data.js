// 배열 무작위 셔플 함수 (Fisher-Yates 알고리즘)
// ============================================================================
function shuffleArray(arr) {
  const result = [...arr];
  for (let i = result.length - 1; i > 0; i--) {
    const j = Math.floor(Math.random() * (i + 1));
    [result[i], result[j]] = [result[j], result[i]];
  }
  return result;
}

// ============================================================================
// 개별 퀴즈 항목의 보기(options) 순서를 무작위로 섞고 정답 인덱스(ans)를 자동 재조정
// 매번 1번이나 2번이 정답이 되지 않고 보기가 무작위로 재배치됨
// ============================================================================
function randomizeQuizQuestion(quiz) {
  if (!quiz || !quiz.options || quiz.options.length < 2) return quiz;
  const correctOptionText = quiz.options[quiz.ans];
  const shuffledOptions = shuffleArray(quiz.options);
  const newAnsIndex = shuffledOptions.indexOf(correctOptionText);

  return {
    ...quiz,
    options: shuffledOptions,
    ans: newAnsIndex >= 0 ? newAnsIndex : 0
  };
}

