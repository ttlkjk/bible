// ============================================================================
// 배열 무작위 셔플 함수 (Fisher-Yates 알고리즘)
// ============================================================================
function shuffleArray(arr) {
  const result = [...arr];
  for (let i = result.length - 1; i > 0; i--) {
    const j = Math.floor(Math.random() * (i + 1));
    [result[i], result[j]] = [result[j], result[i]];
  }
  return result;
}

// ============================================================================
// 개별 퀴즈 항목의 보기(options) 순서를 무작위로 섞고 정답 인덱스(ans)를 자동 재조정
// 매번 1번이나 2번이 정답이 되지 않고 보기가 무작위로 재배치됨
// ============================================================================
function randomizeQuizQuestion(quiz) {
  if (!quiz || !quiz.options || quiz.options.length < 2) return quiz;
  const correctOptionText = quiz.options[quiz.ans];
  const shuffledOptions = shuffleArray(quiz.options);
  const newAnsIndex = shuffledOptions.indexOf(correctOptionText);

  return {
    ...quiz,
    options: shuffledOptions,
    ans: newAnsIndex >= 0 ? newAnsIndex : 0
  };
}

// ============================================================================
// 특정 성경 권의 퀴즈 리스트 반환 함수
// 1) BIBLE_QUIZ_DATABASE 및 BIBLE_BOOKS_DATA 전체 후보군 수집
// 2) 권별 심화 질문 생성(저자, 연대, 요절, 핵심 주제, 에스라 관점, 장별 구조)
// 3) 후보군 풀 전체를 무작위로 섞어 5~7문제를 엄선
// 4) 각 문제의 4가지 보기 순서도 실시간으로 무작위 셔플
// => 새로고침(F5)이나 다시 풀기 클릭 시마다 문제가 매번 새롭게 다양하게 출제됨!
// ============================================================================
function getBookQuizzes(bookId, bookName, count = 6) {
  let pool = [];

  // 1. 전용 퀴즈 DB 조회
  if (BIBLE_QUIZ_DATABASE[bookName]) {
    pool = [...BIBLE_QUIZ_DATABASE[bookName]];
  }

  // 2. BIBLE_BOOKS_DATA 내의 퀴즈와 병합
  if (typeof BIBLE_BOOKS_DATA !== "undefined") {
    const b = BIBLE_BOOKS_DATA.find(item => item.id === bookId || item.name === bookName);
    if (b && b.quizzes && b.quizzes.length > 0) {
      b.quizzes.forEach(bq => {
        if (!pool.some(item => item.q === bq.q)) {
          pool.push(bq);
        }
      });
    }
  }

  // 3. 권별 메타데이터를 활용한 풍부한 맞춤형 문제 풀 동적 생성
  if (typeof BIBLE_BOOKS_DATA !== "undefined") {
    const book = BIBLE_BOOKS_DATA.find(item => item.id === bookId || item.name === bookName);
    if (book) {
      // (1) 기록 목적 및 핵심 주제 문제
      pool.push({
        q: `What best describes the purpose and central theme of [${book.name}]?`,
        options: [
          book.theme,
          "A ruler's strategy manual for seizing worldly political power",
          "A doctrine of enlightenment through philosophical speculation and meditation",
          "Commercial trade ledgers and economics of the ancient Middle East"
        ],
        ans: 0,
        exp: `The central theme of [${book.name}] is "${book.theme}". It was written by ${book.author}, under the inspiration of the Holy Spirit (date of writing: ${book.date}).`
      });

      // (2) 대표 요절 문제
      pool.push({
        q: `What is the most important key verse that captures the thread running through all of [${book.name}]?`,
        options: [
          book.keyVerse,
          "The love of money is the root of all evil",
          "Don't be anxious for tomorrow, for tomorrow will be anxious for itself",
          "Man shall not live by bread alone, but by every word that proceedeth out of the mouth of God"
        ],
        ans: 0,
        exp: `The key verse of [${book.name}] is "${book.keyVerse}".`
      });

      // (3) 노우호 목사 에스라 관점 문제
      pool.push({
        q: `What is the key perspective for reading through [${book.name}] that Pastor Woo-ho Noh's Ezra Bible Course emphasizes?`,
        options: [
          book.ezraPerspective.length > 90 ? book.ezraPerspective.substring(0, 85) + "..." : book.ezraPerspective,
          "It must be read only as a prosperity-gospel formula for blessing, ignoring its historical background",
          "Its parables may be freely interpreted as allegory (allegorical spiritualizing)",
          "It is an old historical record of Israel alone, with nothing to do with New Testament believers"
        ],
        ans: 0,
        exp: `Ezra Bible Course perspective: ${book.ezraPerspective}`
      });

      // (4) 저자 및 기록 시기 문제
      pool.push({
        q: `Which correctly matches the author and historical setting (date of writing) of [${book.name}]?`,
        options: [
          `Author: ${book.author} / Date of writing: ${book.date}`,
          `Author: King Solomon / Date of writing: c. A.D. 100`,
          `Author: Alexander the Great / Date of writing: c. B.C. 300`,
          `Author: the apostle Paul / Date of writing: c. B.C. 1000`
        ],
        ans: 0,
        exp: `[${book.name}] is Scripture written by ${book.author} under the inspiration of the Holy Spirit (date of writing: ${book.date}).`
      });

      // (5) 장별 구조 파트 문제
      if (book.structure && book.structure.length > 0) {
        const firstPart = book.structure[0];
        pool.push({
          q: `In the overall flow of [${book.name}], what is the main content of '${firstPart.part}'?`,
          options: [
            firstPart.content,
            "The fall of the Roman Empire and the genealogies of its emperors",
            "The terms of a real-estate sales contract for land in Canaan",
            "The engineering techniques for building the pyramids of Egypt"
          ],
          ans: 0,
          exp: `The main content of ${firstPart.part} in [${book.name}] is '${firstPart.content}'.`
        });
      }
    }
  }

  // 4. 후보군 전체를 무작위로 섞음 (Random Shuffle)
  const shuffledPool = shuffleArray(pool);

  // 5. 요청된 개수만큼 선택 (기본 5~6문제)
  const selectedCount = Math.min(count, shuffledPool.length);
  const selectedQuizzes = shuffledPool.slice(0, selectedCount);

  // 6. 선택된 각 문제의 4가지 보기(options)도 무작위로 셔플
  return selectedQuizzes.map(q => randomizeQuizQuestion(q));
}

// ============================================================================
// 에스라 성경 골든벨 / 모의고사용 랜덤 N문제 추출 함수
// 전체 성경 풀에서 무작위 추출 + 각 문제 보기 순서 무작위 셔플
// ============================================================================
function getRandomBibleQuizzes(count = 10) {
  const allQuizzes = [];

  // 전체 DB 수집
  Object.keys(BIBLE_QUIZ_DATABASE).forEach(bookName => {
    BIBLE_QUIZ_DATABASE[bookName].forEach(q => {
      allQuizzes.push({ ...q, bookName: bookName });
    });
  });

  // Fisher-Yates 셔플
  const shuffled = shuffleArray(allQuizzes);
  const selected = shuffled.slice(0, Math.min(count, shuffled.length));

  // 각 문제의 보기 순서도 셔플하여 반환
  return selected.map(q => randomizeQuizQuestion(q));
}

